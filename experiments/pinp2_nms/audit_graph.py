"""Inspect ONNX dataflow/parameters without inference or checkpoint deserialization."""
import argparse,hashlib,json
from pathlib import Path
import numpy as np
import onnx

def inspect(path):
 model=onnx.load(path,load_external_data=False);producers={o:i for i,n in enumerate(model.graph.node) for o in n.output};seen=set();ids=set();todo=[o.name for o in model.graph.output]
 while todo:
  value=todo.pop()
  if value in seen:continue
  seen.add(value)
  if value in producers:
   index=producers[value];ids.add(index);todo.extend(model.graph.node[index].input)
 nodes=[model.graph.node[i] for i in ids];weights={v.name:onnx.numpy_helper.to_array(v) for v in model.graph.initializer}
 convolutions={n.name:[weights[x] for x in n.input[1:] if x in weights] for n in nodes if n.op_type=='Conv'}
 result={'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'nodes_in_output_ancestry':len(nodes),'one2one_nodes':sum('one2one' in n.name for n in nodes),'one2many_nodes':sum('one2many' in n.name for n in nodes),'head_non_one2one_cv_nodes':[n.name for n in nodes if '/model.29/cv' in n.name],'NMS_nodes':sum(n.op_type=='NonMaxSuppression' for n in nodes),'outputs':[o.name for o in model.graph.output]}
 return result,convolutions

def main():
 p=argparse.ArgumentParser();p.add_argument('--full',type=Path,required=True);p.add_argument('--raw',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
 full,c1=inspect(a.full);raw,c2=inspect(a.raw);names=set(c1)&set(c2);different=[]
 for name in sorted(names):
  if len(c1[name])!=len(c2[name]) or any(not np.array_equal(x,y) for x,y in zip(c1[name],c2[name])):different.append(name)
 report={'full':full,'raw':raw,'convolution_parameter_check':{'matching_by':'Conv node semantic name and input position, not unstable autogenerated initializer name','shared_Conv_nodes':len(names),'all_weights_biases_bit_identical':not different,'mismatches':different},'scope':'ONNX structural/parameter reading only; no inference. Historical eight-image numerical verification is separate evidence.','script_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
 with a.output.open('x') as f:json.dump(report,f,indent=2);f.write('\n')
 print(json.dumps(report['convolution_parameter_check']))
if __name__=='__main__':main()
